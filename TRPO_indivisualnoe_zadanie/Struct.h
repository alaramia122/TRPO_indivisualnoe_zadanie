#pragma once

#include <string>
#include <vector>

// Результат чтения клавиатурного ввода и признаки нажатых управляющих клавиш.
struct Input_data {

    bool Esc_controller = false;                // true, если пользователь отменил ввод клавишей Esc.

    bool Enter_controller = false;              // true, если пользователь подтвердил ввод клавишей Enter.

    bool Left_controller = false;               // true, если была нажата стрелка влево.

    bool Right_controller = false;              // true, если была нажата стрелка вправо.

    bool Up_controller = false;                 // true, если была нажата стрелка вверх.

    bool Down_controller = false;               // true, если была нажата стрелка вниз.

    bool Del_controller = false;                // true, если была нажата клавиша Delete.

    std::string result;                         // Символы, накопленные до Enter, Esc или стрелки.
};

// Категория распознанного фрагмента исходного HTML-документа.
enum class MyTokenType {

    Open,                                       // Обычный открывающий тег, например <div>.

    Close,                                      // Закрывающий тег, например </div>.

    SelfClose,                                  // Самозакрывающийся тег, например <br/>.

    Comment,                                    // Комментарий HTML, ограниченный маркерами <!-- и -->.

    Text,                                       // Текстовый фрагмент между распознанными тегами.

    Other                                       // Декларация или специальная конструкция (<!DOCTYPE>, <?...>).
};

// Имя и значение одного атрибута открывающего HTML-тега.
struct Attribute {

    std::string name;                           // Имя атрибута.

    std::string value;                          // Значение атрибута после снятия ограничивающих кавычек, если они были.
};

// Токен хранит тип, исходный фрагмент и номер строки для последующей проверки.
struct Token {

    MyTokenType type = MyTokenType::Text;           // Тип токена; по умолчанию обычный текст.

    std::string name;                           // Имя тега для теговых токенов.

    std::string text;                           // Исходное содержимое токена с сохранением значимых символов.

    std::vector<Attribute> attrs;               // Атрибуты, найденные внутри открывающего или самозакрывающегося тега.

    int line = 1;                               // Номер строки исходного документа, начиная с единицы.
};

// Одна обнаруженная проблема с текстовым описанием и номером строки источника.
struct Diagnostic {

    std::string category;                       // Категория проблемы, например лексическая или структурная.

    std::string message;                        // Пояснение, понятное пользователю.

    int line = 1;                               // Строка, в которой обнаружена проблема.
};

// Совокупный результат разбора: токены, диагностики и счётчики элементов документа.
struct AnalysisResult {

    std::vector<Token> tokens;                  // Токены в порядке их появления в исходном тексте.

    std::vector<Diagnostic> diagnostics;        // Ошибки и предупреждения, найденные на этапах анализа.

    int open_tags = 0;                          // Количество обычных открывающих тегов.

    int close_tags = 0;                         // Количество закрывающих тегов.

    int self_tags = 0;                          // Количество самозакрывающихся тегов.

    int attributes = 0;                         // Общее количество разобранных атрибутов.

    int comments = 0;                           // Количество комментариев HTML.

    int texts = 0;                              // Количество сегментов обычного текста.
};