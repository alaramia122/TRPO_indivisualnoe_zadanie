#include "Header.h"

// Точка входа программы: настройка консоли и организация основного пользовательского цикла.
int main() {
    // Настраиваем консоль на русскую кодовую страницу Windows-1251.
    SetConsoleCP(1251);
    SetConsoleOutputCP(1251);

    // Используем альтернативное имя локали для среды Windows.
    if (setlocale(LC_ALL, "ru") == nullptr) {
        setlocale(LC_ALL, "Russian_Russia.1251");
    }

    // Настраиваем контрастную цветовую схему консольного интерфейса.
    system("color F0");
    // До меню показываем пользователю назначение программы и формат входных данных.
    show_start_window();

    // После каждого экрана возвращаемся к меню до выбора пункта выхода.
    while (true) {
        // Меню возвращает числовой код выбранного действия.
        const int choice = show_main_menu();

        // Ветка 1 запускает полный сценарий чтения, разбора и проверки HTML.
        if (choice == 1) {
            const std::string filename = choose_source_file();

            // Пустое имя обозначает отмену выбора или пустой список файлов.
            if (filename.empty()) {
                continue;
            }

            // Входные примеры ожидаются в каталоге SourceTexts относительно рабочей папки.
            const std::string path =
                (fs::path("SourceTexts") / filename).string();

            std::string source;
            std::string error_message;

            // При ошибке чтения показываем сообщение и возвращаемся к меню до вызова парсера.
            if (!read_text_file(path, source, error_message)) {
                // Отделяем сообщение об ошибке от предыдущего содержимого консоли.
                system("cls");

                std::cout << error_message
                          << "\nНажмите любую клавишу для возврата...\n";

                // Даём пользователю прочитать сообщение перед возвратом в меню.
                input_data_reader(true, false, false);
                continue;
            }

            // Результат хранит токены, статистику и диагностики одного выбранного файла.
            HtmlAnalysisResult result;
            // Лексический разбор преобразует исходный текст в типизированные токены.
            parse_html(source, result);
            // Структурная проверка использует токены для анализа вложенности тегов.
            validate_html_structure(result);
            // Показываем сводку только после завершения обеих стадий анализа.
            show_analysis_result(result);
        // Ветка 2 открывает справку напрямую.
        } else if (choice == 2) {
            // После закрытия справки цикл автоматически возвращает пользователя в меню.
            show_about_screen();
        // Остальные коды выбора соответствуют выходу из основного цикла.
        } else {
            break;
        }
    }

    // Сообщаем операционной системе об успешном завершении программы.
    return 0;
}
