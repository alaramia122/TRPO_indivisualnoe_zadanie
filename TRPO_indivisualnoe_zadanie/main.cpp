#include "Header.h"


int main() {                                                // Точка входа программы: настройка консоли и организация основного пользовательского цикла.
    
    SetConsoleCP(CP_UTF8);                                         // Настраиваем консоль на UTF-8.
    SetConsoleOutputCP(CP_UTF8);
    
    system("color F0");                                         // Настраиваем контрастную цветовую схему консольного интерфейса.

    show_start_window();                                        // До меню показываем пользователю назначение программы и формат входных данных.

    while (true) {                                              // После каждого экрана возвращаемся к меню до выбора пункта выхода.

        const int choice = show_main_menu();                        // Меню возвращает числовой код выбранного действия.
        
        if (choice == 1) {                                              // Ветка 1 запускает полный сценарий чтения, разбора и проверки HTML.
            const std::string filename = choose_source_file();
            
            if (filename.empty()) {                                         // Пустое имя обозначает отмену выбора или пустой список файлов.
                continue;
            }

            const std::string path =                                        // Входные примеры ожидаются в каталоге SourceTexts относительно рабочей папки.
                (fs::path("SourceTexts") / fs::u8path(filename)).u8string();

            std::string source;
            std::string error_message;

            if (!read_text_file(path, source, error_message)) {             // При ошибке чтения показываем сообщение и возвращаемся к меню до вызова парсера.
                
                system("cls");                                                  // Отделяем сообщение об ошибке от предыдущего содержимого консоли.
                std::cout << error_message
                          << "\nНажмите любую клавишу для возврата...\n";

                input_data_reader(true, false, false);                          // Даём пользователю прочитать сообщение перед возвратом в меню.
                continue;
            }

            HtmlAnalysisResult result;                                      // Результат хранит токены, статистику и диагностики одного выбранного файла.
            
            parse_html(source, result);                                     // Лексический разбор преобразует исходный текст в типизированные токены.
            
            validate_html_structure(result);                                // Структурная проверка использует токены для анализа вложенности тегов.
            
            show_analysis_result(result, filename);                         // Показываем сводку только после завершения обеих стадий анализа.
        
        } else if (choice == 2) {                                       // Ветка 2 открывает справку напрямую.
            
            show_about_screen();                                            // После закрытия справки цикл автоматически возвращает пользователя в меню.
        
        } else {                                                            // Остальные коды выбора соответствуют выходу из основного цикла.
            break;
        }
    }
    return 0;                                                   // Сообщаем операционной системе об успешном завершении программы.
}
