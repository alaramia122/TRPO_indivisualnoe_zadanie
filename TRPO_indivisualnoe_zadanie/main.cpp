#include "Header.h"

int main() {                                                                // Точка входа программы: настройка консоли и организация основного пользовательского цикла.

    SetConsoleCP(1251);                                                  // Настраиваем консоль на UTF-8.
    SetConsoleOutputCP(1251);

    system("color F0");                                                     // Настраиваем контрастную цветовую схему консольного интерфейса.

    show_start_window();                                                    // До меню показываем пользователю назначение программы и формат входных данных.

	int choice;                                                             // Переменная для хранения кода действия, выбранного пользователем в главном меню.

    while (true) {                                                          // После каждого экрана возвращаемся к меню до выбора пункта выхода.

        choice = show_main_menu();                                          // Меню возвращает числовой код выбранного действия.

        switch (choice) {                                                       // Разветвляем сценарий по коду, возвращённому главным меню.

        case 1: {                                                                   // Ветка 1 запускает сценарий чтения и последующего анализа HTML.

			std::string filename = choose_source_file();                                // Выбираем HTML-файл для анализа; пустая строка означает отмену выбора.

            if (filename.empty()) {                                                     // Пустое имя обозначает отмену выбора или пустой список файлов.
                break;
            }

            std::string path = "SourceTexts/" + filename;                               // Входные примеры ожидаются в каталоге SourceTexts относительно рабочей папки.

            std::vector<std::string> lines;
            std::string error;

            if (!read_file_lines(path, lines, error)) {                                 // При ошибке чтения показываем сообщение и возвращаемся к меню.

                system("cls");                                                              // Отделяем сообщение об ошибке от предыдущего содержимого консоли.
                std::cout << error
                    << "\nНажмите любую клавишу для возврата...\n";

                input_data_reader(true, false, false);                                      // Даём пользователю прочитать сообщение перед возвратом в меню.
                break;
            }

            AnalysisResult result;                                                      // Результат хранит токены, статистику и диагностики одного выбранного файла.

            // Лексический разбор и структурная проверка подключаются после реализации соответствующих модулей.
            // parse_html(lines, result);
            // validate_structure(result);
            // show_analysis_result(result, filename);

            system("cls");
            std::cout << "Файл прочитан: " << filename << "\n";
            std::cout << "Строк: " << lines.size() << "\n";
            std::cout << "Нажмите любую клавишу для возврата...\n";
            input_data_reader(true, false, false);
            break;
        }

        case 2:                                                                     // Ветка 2 открывает справку напрямую.
            show_about_screen();                                                        // После закрытия справки цикл автоматически возвращает пользователя в меню.
            break;

		case 3:                                                                     // Ветка 3 завершает программу.
            return 0;
            break;

        default:                                                                    // Остальные коды выбора ничего не значат.
            break;
        }
    }

    return 0;                                                                   // Сообщаем операционной системе об успешном завершении программы.
}